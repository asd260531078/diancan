function stableId(prefix, categoryIndex, itemIndex, rowIndex) {
  return `${prefix}_menu_v1_${String(categoryIndex + 1).padStart(2, '0')}_${String(itemIndex + 1).padStart(2, '0')}_${String(rowIndex + 1).padStart(2, '0')}`;
}

function getMenuSeedV1() {
  return categories.map((category, categoryIndex) => ({
    name: category.name,
    type: category.type,
    sort: (categoryIndex + 1) * 10,
    enabled: true,
    id: `cat_menu_v1_${String(categoryIndex + 1).padStart(2, '0')}`,
    items: category.items.map((item, itemIndex) => ({
      ...item,
      id: `dish_menu_v1_${String(categoryIndex + 1).padStart(2, '0')}_${String(itemIndex + 1).padStart(2, '0')}`,
      type: category.type,
      mealRoles: category.mealRoles.slice(),
      categoryName: category.name,
      sort: (itemIndex + 1) * 10,
      cover: '',
      images: [],
      price: null,
      recommended: false,
      signature: false,
      availableToday: true,
      soldOut: false,
      enabled: true,
      availableTastePreferences: category.type === 'food' ? (item.availableTastePreferences || []) : [],
      availableCustomRequests: category.type === 'food' ? (item.availableCustomRequests || []) : [],
      availableCupSizes: category.type === 'drink' ? (item.availableCupSizes || []) : [],
      availableSugarLevels: category.type === 'drink' ? (item.availableSugarLevels || []) : [],
      availableTemperatures: category.type === 'drink' ? (item.availableTemperatures || []) : [],
      availableSweetenerTypes: category.type === 'drink' ? (item.availableSweetenerTypes || []) : [],
      availableToppings: category.type === 'drink' ? (item.availableToppings || []) : [],
      ingredients: item.ingredients.map((row, rowIndex) => ({
        id: stableId('ingredient', categoryIndex, itemIndex, rowIndex),
        name: row[0], amount: row[1] || '', note: row[2] || '',
      })),
      steps: item.steps.map((row, rowIndex) => ({
        id: stableId('step', categoryIndex, itemIndex, rowIndex),
        stepNumber: rowIndex + 1,
        title: row[0] || '', description: row[1], image: '',
      })),
    })),
  }));
}

